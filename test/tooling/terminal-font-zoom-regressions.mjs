export async function checkTerminalFontZoom(context, appUrl, screenshotPrefix) {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(appUrl);
  const canvas = page.locator(".terminal-pane.active .terminal-canvas");
  const host = canvas.locator(".terminal-host");
  await host.locator(".xterm-screen").waitFor();
  const waitSize = (p, value) => p.waitForFunction((size) => document.querySelector('.terminal-canvas[data-terminal-focused="true"] .terminal-host')?.dataset.terminalFontSize === String(size), value);
  await waitSize(page, 13);
  const initial = await host.evaluate((el) => ({ size: el.dataset.terminalSize, instance: el.dataset.terminalInstanceId, width: el.querySelector(".xterm-screen").getBoundingClientRect().width }));
  const writes = await page.evaluate(() => window.__invokeCalls.filter((c) => ["send_text", "send_bytes"].includes(c.command)).length);
  await canvas.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(page, 14);
  await host.locator(".xterm-helper-textarea").press("Control+Equal");
  await waitSize(page, 15);
  await host.locator(".xterm-helper-textarea").press("Control+Shift+Equal");
  await waitSize(page, 16);
  await host.locator(".xterm-helper-textarea").press("Control+Minus");
  await waitSize(page, 15);
  await host.locator(".xterm-helper-textarea").press("Control+0");
  await waitSize(page, 13);
  await host.locator(".xterm-helper-textarea").press("Meta+Equal");
  await waitSize(page, 14);
  const blockedWheel = await host.evaluate((el) => !el.dispatchEvent(new WheelEvent("wheel", { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -120 })));
  assert(blockedWheel, "Ctrl+wheel was not prevented");
  await waitSize(page, 15);
  await host.evaluate((el) => el.dispatchEvent(new WheelEvent("wheel", { bubbles: true, cancelable: true, deltaY: -120 })));
  await waitSize(page, 15);
  await page.waitForFunction((oldSize) => document.querySelector(".terminal-pane.active .terminal-host")?.dataset.terminalSize !== oldSize, initial.size);
  assert(await host.getAttribute("data-terminal-instance-id") === initial.instance, "font zoom recreated the terminal");
  assert(await page.evaluate(() => window.__invokeCalls.filter((c) => ["send_text", "send_bytes"].includes(c.command)).length) === writes, "zoom shortcuts were sent to the remote terminal");
  await canvas.getByRole("button", { name: "Hex", exact: true }).click();
  assert(await canvas.getByRole("button", { name: "放大终端字号", exact: true }).isDisabled(), "text zoom was enabled for Hex-only view");
  await canvas.getByRole("button", { name: "文本", exact: true }).click();
  await page.reload();
  await waitSize(page, 15);
  const identity = await canvas.evaluate((el) => ({ session: el.dataset.terminalSessionId, view: el.dataset.terminalViewId }));
  await host.locator(".xterm-helper-textarea").press("Alt+Backslash");
  await page.waitForFunction(() => document.querySelectorAll(".terminal-canvas").length === 2);
  await page.locator(".terminal-pane:not(.active) .workspace-pane-tab").first().click();
  await waitSize(page, 13);
  await canvas.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(page, 14);
  assert(await page.locator(`.terminal-canvas[data-terminal-view-id="${identity.view}"] .terminal-host`).getAttribute("data-terminal-font-size") === "15", "split panes shared font zoom unexpectedly");
  await host.locator(".xterm-helper-textarea").press("Alt+KeyX");
  await waitSize(page, 15);
  const detached = await context.newPage();
  detached.on("pageerror", (error) => errors.push(error.message));
  await detached.goto(`${appUrl}?detachedPane=1&windowId=font-zoom&paneId=font-pane&viewId=independent-font-view&sessionId=${encodeURIComponent(identity.session)}&title=&color=&keyMode=remote`);
  await waitSize(detached, 13);
  // The shared UI harness deliberately clears localStorage on a new page's
  // first load. Restore the main view after that fixture reset.
  await waitSize(page, 13);
  await canvas.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await canvas.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(page, 15);
  await detached.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(detached, 14);
  await waitSize(page, 15);
  // Reusing the original view in a detached window retains and synchronizes its zoom.
  await detached.goto(`${appUrl}?detachedPane=1&windowId=font-zoom&paneId=font-pane&viewId=${encodeURIComponent(identity.view)}&sessionId=${encodeURIComponent(identity.session)}&title=&color=&keyMode=remote`);
  await waitSize(detached, 15);
  await detached.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(detached, 16);
  await detached.waitForFunction(() => window.__invokeCalls.some((c) => c.command === "resize_session"));
  await waitSize(page, 16);
  await detached.close();
  await page.locator(".menu-trigger", { hasText: "工具" }).click();
  await page.getByRole("button", { name: "自定义脚本", exact: true }).click();
  await page.locator(".custom-script-dialog").waitFor();
  await canvas.evaluate((el) => {
    el.querySelector('[aria-label="放大终端字号"]').click();
    el.querySelector(".terminal-host").dispatchEvent(new WheelEvent("wheel", { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -120 }));
  });
  await waitSize(page, 16);
  await page.getByRole("button", { name: "关闭自定义脚本", exact: true }).click();
  await canvas.getByRole("button", { name: "重置终端字号", exact: true }).click();
  await waitSize(page, 13);
  await page.evaluate(() => {
    const session = window.__sessions.find((s) => s.profile.id === "edge-router");
    session.profile.terminal.fontSize = 18;
  });
  await waitSize(page, 18);
  await canvas.getByRole("button", { name: "放大终端字号", exact: true }).click();
  await waitSize(page, 19);
  await canvas.getByRole("button", { name: "重置终端字号", exact: true }).click();
  await waitSize(page, 18);
  await page.screenshot({ path: `${screenshotPrefix}-font-zoom.png`, fullPage: true });
  assert(errors.length === 0, `font zoom browser errors: ${errors.join("; ")}`);
  await page.close();
}
